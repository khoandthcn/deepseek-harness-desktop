#!/usr/bin/env node
// Generate the `standard-brave` agent preset from an upstream `standard` preset.
//
//   node scripts/make-search-preset.mjs <upstream-checkout> <output-dir>
//
// The preset is the shipped `standard` composition with two changes:
//   - the persona suffix carries the Brave Search web search policy
//   - `tool-web` registers only web_fetch (web_search is removed)
// Each edit matches an exact upstream snippet and fails when it is gone.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

export const PRESET_ID = 'standard-brave'

export const WEB_SEARCH_POLICY = [
  'WEB SEARCH POLICY: For every web search task, use the Brave Search HTML + web_fetch technique (the web_search tool is not available).',
  'Fetch https://search.brave.com/search?q=<keywords>, joining keywords with + (or URL-encode them). Always use the exact domain search.brave.com.',
  'Result links point directly at their pages: call web_fetch on a specific result URL to read its full content when needed.',
  'If a fetch fails with a cross-origin redirect error, call web_fetch again on the redirect target URL directly.',
  'If Brave returns a captcha or no results, retry once with rephrased keywords; if it still fails, tell the user that web search is unavailable instead of guessing.',
]

function replaceOnce(text, from, to, label, source) {
  const count = text.split(from).length - 1
  if (count !== 1) throw new Error(`make-search-preset: expected one ${label} block in ${source}, found ${count}`)
  return text.replace(from, to)
}

/**
 * Write `agent.cordis.yml` and `preset.yml` for the Brave Search preset.
 * @param {string} upstream - deepseek-ai/deepseek-harness checkout.
 * @param {string} output - preset directory to create or overwrite.
 */
export function writeSearchPreset(upstream, output) {
  const source = join(upstream, 'packages/preset/agent-presets/presets/standard/agent.cordis.yml')
  let text = readFileSync(source, 'utf8')
  text = replaceOnce(
    text,
    '  config:\n    suffix: Your working directory is {{cwd}}.\n',
    `  config:\n    suffix: |-\n      Your working directory is {{cwd}}.\n\n${WEB_SEARCH_POLICY.map(line => `      ${line}`).join('\n')}\n`,
    'persona suffix',
    source,
  )
  text = replaceOnce(
    text,
    "  name: '@deepseek-ai/dsh-tool-web'\n  config:\n    fetch: true\n",
    "  name: '@deepseek-ai/dsh-tool-web'\n  config:\n    search: false\n    fetch: true\n",
    'tool-web',
    source,
  )
  text = `# Generated by deepseek-harness-desktop/scripts/make-search-preset.mjs from the\n# upstream \`standard\` preset: Brave Search web search policy + no web_search tool.\n\n${text}`

  mkdirSync(output, { recursive: true })
  writeFileSync(join(output, 'agent.cordis.yml'), text)
  writeFileSync(join(output, 'preset.yml'), [
    'name: Standard (Brave Search)',
    'description: Full coding agent; web search goes through Brave Search HTML + web_fetch instead of web_search.',
    'order: 2',
    '',
  ].join('\n'))
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const upstream = resolve(process.argv[2] ?? '.work/upstream')
  const output = resolve(process.argv[3] ?? `presets/${PRESET_ID}`)
  writeSearchPreset(upstream, output)
  console.log(`wrote ${output}`)
}
