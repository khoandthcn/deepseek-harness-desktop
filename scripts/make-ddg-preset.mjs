#!/usr/bin/env node
// Generate the `standard-ddg` agent preset from an upstream `standard` preset.
//
//   node scripts/make-ddg-preset.mjs <upstream-checkout> <output-dir>
//
// The preset is the shipped `standard` composition with two changes:
//   - the persona suffix carries the DuckDuckGo web search policy
//   - `tool-web` registers only web_fetch (web_search is removed)
// Each edit matches an exact upstream snippet and fails when it is gone.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

export const PRESET_ID = 'standard-ddg'

export const WEB_SEARCH_POLICY = [
  'WEB SEARCH POLICY: For every web search task, use the DuckDuckGo HTML + web_fetch technique (the web_search tool is not available).',
  'Fetch https://html.duckduckgo.com/html/?q=<keywords>, joining keywords with + (or URL-encode them).',
  'CRITICAL: always use the exact domain html.duckduckgo.com; if you hit a cross-origin redirect error, retry that exact URL directly.',
  'Result links may be DuckDuckGo redirect links such as //duckduckgo.com/l/?uddg=<encoded-url>: URL-decode the uddg value and call web_fetch on that real URL instead.',
  'From the returned result list, use web_fetch on a specific URL to read full page content when needed.',
]

function replaceOnce(text, from, to, label, source) {
  const count = text.split(from).length - 1
  if (count !== 1) throw new Error(`make-ddg-preset: expected one ${label} block in ${source}, found ${count}`)
  return text.replace(from, to)
}

/**
 * Write `agent.cordis.yml` and `preset.yml` for the DuckDuckGo preset.
 * @param {string} upstream - deepseek-ai/deepseek-harness checkout.
 * @param {string} output - preset directory to create or overwrite.
 */
export function writeDdgPreset(upstream, output) {
  const source = join(upstream, 'packages/preset/agent-presets/presets/standard/agent.cordis.yml')
  let text = readFileSync(source, 'utf8')
  text = replaceOnce(
    text,
    '  config:\n    suffix: Your working directory is {{cwd}}.\n',
    `  config:\n    suffix: |-\n      Your working directory is {{cwd}}.\n\n${WEB_SEARCH_POLICY.map(line => `      ${line}`).join('\n')}\n`,
    'persona suffix',
    source,
  )
  text = replaceOnce(
    text,
    "  name: '@deepseek-ai/dsh-tool-web'\n  config:\n    fetch: true\n",
    "  name: '@deepseek-ai/dsh-tool-web'\n  config:\n    search: false\n    fetch: true\n",
    'tool-web',
    source,
  )
  text = `# Generated by deepseek-harness-desktop/scripts/make-ddg-preset.mjs from the\n# upstream \`standard\` preset: DuckDuckGo web search policy + no web_search tool.\n\n${text}`

  mkdirSync(output, { recursive: true })
  writeFileSync(join(output, 'agent.cordis.yml'), text)
  writeFileSync(join(output, 'preset.yml'), [
    'name: Standard (DuckDuckGo)',
    'description: Full coding agent; web search goes through DuckDuckGo HTML + web_fetch instead of web_search.',
    'order: 2',
    '',
  ].join('\n'))
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const upstream = resolve(process.argv[2] ?? '.work/upstream')
  const output = resolve(process.argv[3] ?? `presets/${PRESET_ID}`)
  writeDdgPreset(upstream, output)
  console.log(`wrote ${output}`)
}
